import type { Address, Hex } from "viem";
import type { PoolReserves } from "./launchTrade";

/**
 * Stand-ins the browser tests (e2e/orders.spec) give the page in place of what it can't get there: a logged-in CRUX
 * Account (the real one needs a Privy login) and a pool's market state. Honoured only in a build made with
 * NEXT_PUBLIC_CHART_HARNESS=1 (the test build); in the live site's build this is a constant false and the code is
 * dropped.
 */
export const TEST_BUILD = process.env.NEXT_PUBLIC_CHART_HARNESS === "1";

export type TestOverrides = {
  /** A CRUX Account owned by a throwaway test key (generated by the test, never funded anywhere). */
  account?: { ownerKey: Hex; account: Address; withdrawalAddress: Address; usdc: bigint };
  /** A graduated launch's market, by token address (lowercase). */
  market?: Record<string, { reserves: PoolReserves; decimals: number; listed: boolean; protected?: boolean; protectedUntil?: number }>;
};

declare global {
  interface Window {
    __cruxTest?: TestOverrides;
  }
}

export function testOverride<K extends keyof TestOverrides>(key: K): TestOverrides[K] | undefined {
  if (!TEST_BUILD || typeof window === "undefined") return undefined;
  return window.__cruxTest?.[key];
}
