export const DICTIONARIES: Record<Lang, Dict> = { en, zh, es, ko, ru };

/** The string for a key in a language, with {name} placeholders filled in. Falls back to English. */
export function translate(lang: Lang, key: Key, vars?: Record<string, string | number>): string {
  const template: string = DICTIONARIES[lang][key] ?? en[key] ?? key;
  return vars ? template.replace(/\{(\w+)\}/g, (m, name: string) => (name in vars ? String(vars[name]) : m)) : template;
}
